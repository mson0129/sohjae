loader="""
const assets=new Map();
async function binary(name){
  if(location.protocol!=='file:')return new URL(name,document.baseURI);
  if(!assets.has(name))assets.set(name,new Promise((resolve,reject)=>{
    const script=document.createElement('script');script.src='./'+name+'.js';
    script.onload=()=>resolve(window.SohjaeExampleWasm[name]);script.onerror=()=>reject(new Error(name+' 로딩 실패'));document.head.append(script);
  }));
  return assets.get(name);
}
const status=document.querySelector('#status');
function report(error){status.textContent=error.message;status.dataset.error='true';console.error(error);}
"""
initial='# 한글 Markdown 예제😀\n\n**굵게**, *기울임*, ==하이라이트==를 확인하세요.\n\n- [x] WASM으로 렌더링\n- [ ] 내용을 직접 편집\n\n| 항목 | 상태 |\n| --- | :---: |\n| 표 편집 | 준비 |\n| 한글 입력 | 준비 |\n'

def bundle(modules,entry):
    factories=[]
    for name in modules:
        source=(web/name).read_text();exports=[]
        def resolve(path):return posixpath.normpath(posixpath.join(posixpath.dirname(name),path))
        def import_statement(m):return 'const {'+m[1]+'}=await load('+json.dumps(resolve(m[2]))+');'
        source=re.sub(r"^import\s*\{([^}]+)\}\s*from\s*['\"]([^'\"]+)['\"];?",import_statement,source,flags=re.M)
        def reexport(m):
            names=[s.strip() for s in m[1].split(',')]
            return 'Object.assign(exports,(({' + ','.join(names)+'})=>({' + ','.join(names)+'}))(await load('+json.dumps(resolve(m[2]))+')));'
        source=re.sub(r"^export\s*\{([^}]+)\}\s*from\s*['\"]([^'\"]+)['\"];?",reexport,source,flags=re.M)
        for m in re.finditer(r'^export\s+(?:async\s+)?(?:function|class|const)\s+(\w+)',source,re.M):exports.append(m[1])
        source=re.sub(r'^export\s+','',source,flags=re.M)
        source=re.sub(r"import\(['\"]([^'\"]+)['\"]\)",lambda m:'load('+json.dumps(resolve(m[1]))+')',source)
        source=source.replace('import.meta.url','new URL('+json.dumps(name)+',document.baseURI).href')
        source+='\nObject.assign(exports,{'+','.join(exports)+'});'
        factories.append(json.dumps(name)+':async(load,exports)=>{\n'+source+'\n}')
    return "// Generated by scripts/build_examples.py. MIT; edit web/ sources.\n(()=>{\nconst factories={"+',\n'.join(factories)+"};\nconst cache=new Map();function load(name){if(!cache.has(name)){const factory=factories[name];if(!factory)throw new Error('Unknown module '+name);cache.set(name,(async()=>{const exports={};await factory(load,exports);return exports;})());}return cache.get(name);}\n"+loader+'\n(async()=>{\n'+entry+'\n})().catch(report);\n})();\n'

editor_modules=['core.js','clipboard.js','editor.js']
settings='css_text:'+json.dumps((web/'editor.css').read_text(),ensure_ascii=False)+',mode:"rich"'
